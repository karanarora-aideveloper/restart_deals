/**
 * Resolves a URL slug (e.g. "supplements" or "audio") into full category/subcategory config.
 */
export function resolveBestCategory(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();

  // 1. Direct match from curated slugs
  if (TOP_CURATED_BEST_SLUGS[cleanSlug]) {
    return { slug: cleanSlug, ...TOP_CURATED_BEST_SLUGS[cleanSlug] };
  }

  // 2. Direct match against subcategory taxonomy labels
  if (SUBCATEGORY_LABELS[cleanSlug]) {
    const label = SUBCATEGORY_LABELS[cleanSlug];
    return {
      slug: cleanSlug,
      subcategory: cleanSlug,
      title: `Top 20 Best ${label} in India`,
      heading: `Top 20 Best ${label} in India (2026)`,
      subtitle: `Real-time price comparison and 90-day price drop history for ${label} across Amazon, Flipkart & top stores.`,
      keyword: `best ${label.toLowerCase()} in india`,
      description: `Top 20 best ${label} in India. Live price comparison across Amazon, Flipkart and Myntra with verified discounts.`,
      tips: [
        'Check customer reviews and star rating distribution before buying.',
        'Verify against our 90-day price tracker to confirm genuine price drop.'
      ]
    };
  }

  // 3. Fallback: humanize slug
  const humanized = cleanSlug.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
  return {
    slug: cleanSlug,
    subcategory: cleanSlug,
    title: `Top 20 Best ${humanized} in India`,
    heading: `Top 20 Best ${humanized} in India (2026)`,
    subtitle: `Real-time price comparison across Amazon, Flipkart, Myntra & Shopsy.`,
    keyword: `best ${humanized.toLowerCase()} in india`,
    description: `Top 20 best ${humanized} in India. Live price comparison with verified discounts.`,
    tips: ['Check price history and authentic user reviews before purchasing.']
  };
}
