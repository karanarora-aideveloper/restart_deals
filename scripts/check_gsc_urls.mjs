async function checkUrl(url) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 7000);
  try {
    const res = await fetch(url, {
      method: 'GET',
      headers: {
        'User-Agent': 'Mozilla/5.0 (compatible; Googlebot/2.1; +http://www.google.com/bot.html)',
        'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
      },
      signal: controller.signal,
      redirect: 'manual', // observe exact 301/302 vs 200 vs 404
    });
    clearTimeout(timeout);
    return {
      url,
      status: res.status,
      ok: res.status >= 200 && res.status < 400,
      location: res.headers.get('location') || null,
    };
  } catch (err) {
    clearTimeout(timeout);
    return {
      url,
      status: err.name === 'AbortError' ? 'TIMEOUT' : 'ERROR',
      ok: false,
      error: err.message,
    };
  }
}

// Concurrency runner
async function runAll(concurrency = 12) {
  const results = [];
  const queue = [...uniqueUrls];
  let completed = 0;

  async function worker() {
    while (queue.length > 0) {
      const u = queue.shift();
      const r = await checkUrl(u);
      results.push(r);
      completed++;
      if (completed % 25 === 0 || completed === uniqueUrls.length) {
        console.log(`Checked ${completed}/${uniqueUrls.length} URLs...`);
      }
    }
  }

  const workers = Array.from({ length: concurrency }, () => worker());
  await Promise.all(workers);

  // Group by status
  const byStatus = {};
  results.forEach(r => {
    byStatus[r.status] = (byStatus[r.status] || 0) + 1;
  });

  const broken = results.filter(r => !r.ok);
  const working = results.filter(r => r.ok);

  console.log("\n================ RESULTS SUMMARY ================");
  console.log("Total Checked:", results.length);
  console.log("Status Breakdown:", byStatus);
  console.log(`Working (200/Redirects): ${working.length}`);
  console.log(`Broken (404/Error): ${broken.length}`);

  if (broken.length > 0) {
    console.log("\nSample Broken URLs (first 20):");
    broken.slice(0, 20).forEach(b => console.log(`[${b.status}] ${b.url}`));
  }

  fs.writeFileSync('scripts/gsc_audit_results.json', JSON.stringify({
    total: results.length,
    byStatus,
    workingCount: working.length,
    brokenCount: broken.length,
    broken,
    results
  }, null, 2));
}

